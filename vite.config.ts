import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = dirname(fileURLToPath(import.meta.url));
/**
 * Vite reads `.env.[mode].local`, and `vite build` runs in mode "production" — so a file
 * named for development is one a production build cannot load, whatever is left in it.
 * That is the whole reason for the name. It used to be `.env.local`, which every mode
 * loads: a build run after a dev session put all four private keys into `dist/`.
 */
const envLocalPath = join(repoRoot, ".env.development.local");
/** The old name, removed on sight so a contaminated checkout cleans itself up. */
const stalePath = join(repoRoot, ".env.local");
/**
 * Where the curator key goes for a production build.
 *
 * `vite build` runs in mode "production", so this is the file it loads and the dev one is
 * not. Both are `.env*.local`, so both are gitignored; the value inside this one is
 * public on purpose and the other's never is.
 */
const envProdPath = join(repoRoot, ".env.production.local");

/**
 * Every secret the demo needs is injected here and ONLY when running `vite` in dev
 * (`command === "serve"`). A production build receives empty values, `canWrite()` turns
 * false, and the write panels fall back to read-only (ADR 0011).
 *
 * This must stay the single door for secrets: importing `data/accounts.json` from
 * application code would inline the owner keys into the built bundle, which would then
 * publish three funded accounts the moment `dist/` is deployed.
 */
function curatorKey(): string {
  const env = loadEnv("", join(repoRoot, "contracts"), "");
  // `process.env` as well as the file, because CI has no `contracts/.env` — GitHub Pages
  // passes this in as a repository *variable*, not a secret, which is the correct kind
  // for a value that is about to be published inside the bundle.
  return env["CURATOR_PRIVATE_KEY"] ?? process.env["CURATOR_PRIVATE_KEY"] ?? "";
}

function devOnlySecrets(isDev: boolean): { submitterKey: string; ownerKeys: Record<string, string> } {
  if (!isDev) return { submitterKey: "", ownerKeys: {} };
  const env = loadEnv("", join(repoRoot, "contracts"), "");
  const accountsPath = join(repoRoot, "data", "accounts.json");
  const accounts = existsSync(accountsPath)
    ? (JSON.parse(readFileSync(accountsPath, "utf-8")) as { keys?: Record<string, string> })
    : {};
  return { submitterKey: env["PRIVATE_KEY"] ?? "", ownerKeys: accounts.keys ?? {} };
}

/**
 * Writes the dev-only secrets where Vite's own env loader will find them.
 *
 * Rewritten on every start so it tracks `data/accounts.json`: renaming the roles there
 * once left a stale file behind and the app opened read-only for no visible reason.
 */
function writeEnvLocal(
  secrets: { submitterKey: string; ownerKeys: Record<string, string> },
  rpc: string,
  curator: string,
): void {
  const body = [
    "# Generated by vite.config.ts on every dev start. Gitignored — never commit.",
    "# Named for the dev mode on purpose: `vite build` runs as production and cannot read it.",
    `DEMO_SUBMITTER_KEY=${secrets.submitterKey}`,
    `DEMO_OWNER_KEYS=${JSON.stringify(secrets.ownerKeys)}`,
    `DEMO_RPC=${rpc}`,
    `VITE_CURATOR_KEY=${curator}`,
    "",
  ].join("\n");
  writeFileSync(envLocalPath, body);
}

/**
 * The one key a production build is *meant* to carry.
 *
 * Everything else here exists to keep keys out of `dist/`. This is the exception, and it
 * is deliberate: the curator is the single attestor every signed delegation names, so a
 * hosted visitor who mints a domain has to stake its edge for that address or the domain
 * authorizes nothing. The alternative was a server holding the key and approving each
 * visitor; a testnet burner in the open is simpler and worth less.
 *
 * The `VITE_` prefix carries that distinction: in this project `DEMO_*` is a dev-only
 * secret and `VITE_*` is public. `bun run build` still greps the bundle for every other
 * key, and still refuses it.
 */
function writeEnvProd(curator: string): void {
  writeFileSync(
    envProdPath,
    [
      "# Generated by vite.config.ts on every build. Gitignored.",
      "# PUBLIC BY DESIGN — this one key ships inside dist/. See ADR 0029.",
      `VITE_CURATOR_KEY=${curator}`,
      "",
    ].join("\n"),
  );
}

/**
 * Forgets the dev secrets before a production build — on disk and in the environment.
 *
 * Deleting the file was all this used to do, and it stopped nothing: a build run after a
 * dev session put all four private keys into `dist/`, then removed the file, so the
 * checkout looked clean afterwards.
 *
 * Two separate reasons, which is why it takes two lines. Vite resolves the env before it
 * calls this config, so the unlink lands after the values are already read. And `bun run
 * build` is bun running vite: bun loads `.env*` files into `process.env` itself, before
 * vite exists at all, and `loadEnv` merges prefixed names from `process.env` — so no
 * amount of unlinking inside vite can be early enough. The variables have to be dropped
 * where they actually are.
 *
 * `bun run build` greps the bundle for the real key material afterwards. That check, not
 * this function, is what proves ADR 0011's claim.
 */
function clearEnvLocal(): void {
  for (const path of [envLocalPath, stalePath]) if (existsSync(path)) rmSync(path);
  for (const name of Object.keys(process.env)) {
    if (name.startsWith("DEMO_")) delete process.env[name];
  }
}

export default defineConfig(({ command }) => {
  const isDev = command === "serve";
  const secrets = devOnlySecrets(isDev);
  const curator = curatorKey();
  const env = loadEnv("", join(repoRoot, "contracts"), "");
  if (isDev) {
    writeEnvLocal(secrets, env["INTUITION_TESTNET_RPC"] ?? "", curator);
  } else {
    // Purge first, write second: `clearEnvLocal` drops every `DEMO_*` from `process.env`,
    // and the curator key is written after that so the purge cannot take it with them.
    clearEnvLocal();
    writeEnvProd(curator);
  }
  return {
    root: repoRoot,
    // Relative, so the build does not know what the repository is called. It was
    // "/Liquid-demo/", which 404s every asset the moment the repo is renamed or
    // transferred — and it is about to be transferred. A single-page app needs no
    // absolute base.
    base: isDev ? "/" : "./",
    plugins: [react()],
    /**
     * Secrets reach the app through a generated, gitignored `.env.development.local`
     * rather than
     * through `define`. Vite 8 leaves a `define` substitution untouched in the modules it
     * serves in dev — it only lands in a production build — so the app threw on a name
     * that did not exist. Loading them as env vars works the same way in both modes.
     */
    envPrefix: ["VITE_", "DEMO_"],
    server: {
      port: 5173,
      /**
       * `allow: [repoRoot]` is what lets the dev server read the manifest and the signed
       * delegations off disk. It also served `data/accounts.json` — the three owner
       * private keys — to anything that could reach the port, status 200, in the clear.
       * Vite's default deny list covers `.env*`, which is why `contracts/.env` was
       * already 403; it knows nothing about this file, so it is named here. Restating
       * the defaults because setting `deny` replaces them.
       */
      fs: {
        allow: [repoRoot],
        deny: [".env", ".env.*", "*.{crt,pem}", "**/accounts.json"],
      },
    },
    build: { outDir: "dist" },
  };
});
